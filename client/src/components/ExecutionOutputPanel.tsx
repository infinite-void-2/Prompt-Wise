import React, { useState } from 'react';
import {
  Check,
  Clock,
  Copy,
  Cpu,
  Hash,
  Sparkles,
  ThumbsDown,
  ThumbsUp,
  Send,
} from 'lucide-react';
import { submitFeedback } from '../lib/api.js';
import { getModelDisplayName } from '../lib/models.js';
import { ExecutionResult } from '../types/index.js';

interface ExecutionOutputPanelProps {
  result: ExecutionResult;
  variantType: 'original' | 'highContext' | 'lowToken' | 'custom';
}

export const ExecutionOutputPanel: React.FC<ExecutionOutputPanelProps> = React.memo(({
  result,
  variantType,
}) => {
  const [copied, setCopied] = useState(false);
  const [feedbackRating, setFeedbackRating] = useState<'helpful' | 'not_helpful' | null>(null);
  const [feedbackReason, setFeedbackReason] = useState('');
  const [feedbackSubmitted, setFeedbackSubmitted] = useState(false);
  const [isSubmittingFeedback, setIsSubmittingFeedback] = useState(false);

  const modelInfo = getModelDisplayName(result.model);
  const variantLabel =
    variantType === 'highContext'
      ? 'High-Context Variant'
      : variantType === 'lowToken'
      ? 'Low-Token Variant'
      : variantType === 'original'
      ? 'Original Prompt'
      : 'Custom Variant';

  const handleCopy = async () => {
    try {
      if (navigator.clipboard && typeof navigator.clipboard.writeText === 'function') {
        await navigator.clipboard.writeText(result.response);
      } else {
        throw new Error('Clipboard API unavailable');
      }
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      try {
        const textarea = document.createElement('textarea');
        textarea.value = result.response;
        textarea.style.position = 'fixed';
        textarea.style.left = '-999999px';
        textarea.style.top = '-999999px';
        document.body.appendChild(textarea);
        textarea.focus();
        textarea.select();
        document.execCommand('copy');
        document.body.removeChild(textarea);
        setCopied(true);
        setTimeout(() => setCopied(false), 2000);
      } catch {
        // Non-fatal copy error
      }
    }
  };

  const handleSendFeedback = async () => {
    if (!feedbackRating) return;
    setIsSubmittingFeedback(true);
    try {
      await submitFeedback({
        requestId: result.requestId,
        variantType,
        rating: feedbackRating,
        reason: feedbackReason.trim() || undefined,
      });
      setFeedbackSubmitted(true);
    } catch {
      // Non-fatal feedback error
    } finally {
      setIsSubmittingFeedback(false);
    }
  };

  return (
    <div
      id="execution-output-card"
      className="glass-panel-glow rounded-2xl p-6 border border-[#282A2C] shadow-xl space-y-4 transition-all"
    >
      {/* Top Header: Title & Copy Button */}
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-[#282A2C] pb-3">
        <div className="flex items-center space-x-3">
          <div className="w-10 h-10 rounded-xl bg-[#1E2E25] text-[#81C995] flex items-center justify-center border border-[#2E573D]">
            <Sparkles className="w-5 h-5" />
          </div>
          <div className="space-y-0.5">
            <div className="flex flex-wrap items-center gap-2">
              <h2 className="text-base font-bold text-white tracking-tight">
                Execution Output
              </h2>
              <span className="px-2.5 py-0.5 rounded-full text-xs font-bold bg-[#1E2E25] border border-[#2E573D] text-[#81C995] flex items-center gap-1">
                <Cpu className="w-3 h-3 text-[#81C995]" />
                <span>{modelInfo.name}</span>
              </span>
              <span className="px-2 py-0.5 rounded-md text-[10px] font-bold bg-[#282A2C] text-[#C4C7C5] border border-[#3C4043] tracking-wider uppercase">
                {modelInfo.providerName}
              </span>
              <span className="px-2 py-0.5 rounded-md text-[10px] font-semibold bg-[#1E2838] text-[#8AB4F8] border border-[#2B3E5A]">
                {variantLabel}
              </span>
            </div>
            <p className="text-xs text-[#9AA0A6] flex items-center gap-1.5">
              <span>Generated by AI model:</span>
              <code className="text-[#81C995] font-mono text-[11px] bg-[#131314] px-1.5 py-0.5 rounded border border-[#282A2C] font-semibold">
                {result.model}
              </code>
            </p>
          </div>
        </div>

        <button
          type="button"
          onClick={handleCopy}
          id="copy-execution-response-btn"
          aria-label="Copy execution response text"
          className="flex items-center space-x-1.5 px-3.5 py-1.5 rounded-lg text-xs font-semibold bg-[#282A2C] hover:bg-[#3C4043] text-[#E3E3E3] border border-[#3C4043] transition-colors shadow-sm focus-visible:ring-2 focus-visible:ring-[#8AB4F8]"
        >
          {copied ? (
            <>
              <Check className="w-3.5 h-3.5 text-[#81C995]" />
              <span className="text-[#81C995]">Response Copied!</span>
            </>
          ) : (
            <>
              <Copy className="w-3.5 h-3.5 text-[#9AA0A6]" />
              <span>Copy Response</span>
            </>
          )}
        </button>
      </div>

      {/* Metadata Bar */}
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5 text-xs">
        <div className="flex items-center space-x-2.5 bg-[#131314] p-2.5 rounded-xl border border-[#2E573D]/60">
          <Cpu className="w-4 h-4 text-[#81C995] flex-shrink-0" />
          <div className="min-w-0">
            <span className="text-[10px] text-[#9AA0A6] uppercase tracking-wider block font-semibold">Generating Model</span>
            <span className="font-semibold text-[#81C995] text-xs truncate block">{modelInfo.name}</span>
            <span className="text-[9px] text-[#9AA0A6] font-mono truncate block">{result.model}</span>
          </div>
        </div>

        <div className="flex items-center space-x-2 bg-[#131314] p-2.5 rounded-xl border border-[#2B3E5A]/60">
          <Clock className="w-3.5 h-3.5 text-[#8AB4F8] flex-shrink-0" />
          <div>
            <span className="text-[10px] text-[#9AA0A6] block font-semibold uppercase tracking-wider">Observed Latency</span>
            <span className="font-mono font-semibold text-[#8AB4F8]">{result.latencyMs} ms</span>
          </div>
        </div>

        <div className="flex items-center space-x-2 bg-[#131314] p-2.5 rounded-xl border border-[#282A2C]">
          <Hash className="w-3.5 h-3.5 text-[#81C995] flex-shrink-0" />
          <div>
            <span className="text-[10px] text-[#9AA0A6] block font-semibold uppercase tracking-wider">Input Tokens</span>
            <span className="font-mono font-semibold text-[#81C995]">
              {result.usage?.promptTokens ?? 'N/A'}
            </span>
          </div>
        </div>

        <div className="flex items-center space-x-2 bg-[#131314] p-2.5 rounded-xl border border-[#282A2C]">
          <Hash className="w-3.5 h-3.5 text-[#C58AF9] flex-shrink-0" />
          <div>
            <span className="text-[10px] text-[#9AA0A6] block font-semibold uppercase tracking-wider">Output Tokens</span>
            <span className="font-mono font-semibold text-[#C58AF9]">
              {result.usage?.candidateTokens ?? 'N/A'}
            </span>
          </div>
        </div>
      </div>

      {/* Response Model Indicator Pill */}
      <div className="flex items-center justify-between text-[11px] text-[#9AA0A6] px-1 pt-1">
        <span className="flex items-center gap-1.5">
          <Sparkles className="w-3.5 h-3.5 text-[#81C995]" />
          <span>Output generated by <strong className="text-[#E3E3E3]">{modelInfo.name}</strong> ({modelInfo.providerName})</span>
        </span>
        <span className="font-mono text-[#9AA0A6] text-[10px]">{new Date(result.timestamp || Date.now()).toLocaleTimeString()}</span>
      </div>

      {/* Response Text Output */}
      <div className="bg-[#131314] rounded-xl p-4 border border-[#282A2C] max-h-96 overflow-y-auto">
        <pre className="text-xs font-mono text-[#E3E3E3] whitespace-pre-wrap leading-relaxed select-text">
          {result.response}
        </pre>
      </div>

      {/* User Feedback Widget (FR-7) */}
      <div className="border-t border-[#282A2C] pt-3 flex flex-wrap items-center justify-between gap-3 text-xs">
        <div className="flex items-center space-x-2">
          <span className="text-[#9AA0A6]">Was this response helpful?</span>
          {!feedbackSubmitted ? (
            <div className="flex items-center space-x-1">
              <button
                type="button"
                onClick={() => setFeedbackRating('helpful')}
                className={`p-1.5 rounded-lg border transition-colors focus-visible:ring-2 focus-visible:ring-[#81C995] ${
                  feedbackRating === 'helpful'
                    ? 'bg-[#1E2E25] border-[#2E573D] text-[#81C995]'
                    : 'bg-[#282A2C] border-[#3C4043] text-[#9AA0A6] hover:text-[#E3E3E3]'
                }`}
                title="Helpful"
                id="feedback-helpful-btn"
                aria-label="Rate response as helpful"
              >
                <ThumbsUp className="w-3.5 h-3.5" />
              </button>
              <button
                type="button"
                onClick={() => setFeedbackRating('not_helpful')}
                className={`p-1.5 rounded-lg border transition-colors focus-visible:ring-2 focus-visible:ring-[#F28B82] ${
                  feedbackRating === 'not_helpful'
                    ? 'bg-[#3B181A] border-[#6B2529] text-[#F28B82]'
                    : 'bg-[#282A2C] border-[#3C4043] text-[#9AA0A6] hover:text-[#E3E3E3]'
                }`}
                title="Not helpful"
                id="feedback-not-helpful-btn"
                aria-label="Rate response as not helpful"
              >
                <ThumbsDown className="w-3.5 h-3.5" />
              </button>
            </div>
          ) : (
            <span className="text-[#81C995] font-medium">Thank you for your feedback!</span>
          )}
        </div>

        {feedbackRating && !feedbackSubmitted && (
          <div className="flex items-center space-x-2 w-full sm:w-auto">
            <input
              type="text"
              value={feedbackReason}
              onChange={(e) => setFeedbackReason(e.target.value)}
              placeholder="Optional: reason (e.g. format followed perfectly)"
              aria-label="Feedback reason"
              className="bg-[#131314] text-[#E3E3E3] text-xs px-3 py-1.5 rounded-lg border border-[#3C4043] focus:outline-none focus:ring-1 focus:ring-[#8AB4F8] flex-1 sm:w-64"
            />
            <button
              type="button"
              onClick={handleSendFeedback}
              disabled={isSubmittingFeedback}
              aria-label="Submit feedback"
              className="flex items-center space-x-1 px-3 py-1.5 rounded-lg bg-[#1A73E8] hover:bg-[#1B66CA] text-white font-medium text-xs transition-colors focus-visible:ring-2 focus-visible:ring-[#8AB4F8]"
            >
              <Send className="w-3 h-3" />
              <span>Submit</span>
            </button>
          </div>
        )}
      </div>
    </div>
  );
});

ExecutionOutputPanel.displayName = 'ExecutionOutputPanel';
